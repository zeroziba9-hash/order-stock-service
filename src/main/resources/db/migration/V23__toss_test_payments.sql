CREATE TABLE toss_payments (
    id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    sequence BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
    order_id BIGINT NOT NULL,
    request_key VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    amount BIGINT NOT NULL,
    customer_key VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status VARCHAR(20) NOT NULL,
    payment_key VARCHAR(200) CHARACTER SET ascii COLLATE ascii_bin NULL,
    confirm_key VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    refund_key VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payment_id BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    confirm_started_at DATETIME(6) NULL,
    refund_started_at DATETIME(6) NULL,
    next_check_at DATETIME(6) NULL,
    claim_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    attempts INT NOT NULL DEFAULT 0,
    last_hint_at DATETIME(6) NULL,
    outbound_disabled BOOLEAN NOT NULL DEFAULT FALSE,
    active_order_id BIGINT GENERATED ALWAYS AS
        (CASE WHEN status IN ('READY','CONFIRMING','UNKNOWN','PAID','CANCELING') THEN order_id ELSE NULL END) STORED,
    CONSTRAINT fk_toss_order FOREIGN KEY (order_id) REFERENCES purchase_orders(id),
    CONSTRAINT fk_toss_payment FOREIGN KEY (payment_id) REFERENCES payment_attempts(id),
    CONSTRAINT uq_toss_request UNIQUE (order_id, request_key),
    CONSTRAINT uq_toss_active UNIQUE (active_order_id),
    CONSTRAINT uq_toss_payment_key UNIQUE (payment_key),
    CONSTRAINT ck_toss_amount CHECK (amount > 0 AND amount <= 9007199254740991),
    CONSTRAINT ck_toss_status CHECK (status IN ('READY','CONFIRMING','UNKNOWN','PAID','CANCELING','CANCELED','FAILED')),
    INDEX idx_toss_due (next_check_at, id),
    INDEX idx_toss_order (order_id, sequence)
) ENGINE=InnoDB;
