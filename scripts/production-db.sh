#!/usr/bin/env bash
set -euo pipefail
umask 077

fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
usage() {
    printf '%s\n' \
        'Usage: bash scripts/production-db.sh backup ENV_FILE BACKUP_PARENT [PROJECT]' \
        '       bash scripts/production-db.sh restore ENV_FILE ARCHIVE_DIRECTORY PROJECT' >&2
    exit 2
}

[[ $# -ge 3 && $# -le 4 ]] || usage
operation=$1
[[ $operation == backup || $operation == restore ]] || usage
[[ $operation != restore || $# -eq 4 ]] || usage
env_file=$(realpath -- "$2")
[[ -f $env_file && -r $env_file ]] || fail 'Environment file is not readable.'
project=${4:-order-stock-prod}
[[ $project =~ ^[a-z0-9][a-z0-9_-]*$ ]] || fail 'Invalid Compose project name.'
repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
compose=(docker compose --project-name "$project" --env-file "$env_file" -f "$repo_root/deploy/compose.prod.yaml")

# Passwords stay inside the DB container, outside host command arguments and output.
# shellcheck disable=SC2016 # Expand these variables in the container's sh, not on the host.
mysql_command='MYSQL_PWD="$MYSQL_PASSWORD" exec mysql --protocol=TCP --host=127.0.0.1 --user="$MYSQL_USER" --database="$MYSQL_DATABASE" --batch --skip-column-names'
query() { printf '%s\n' "$1" | "${compose[@]}" exec -T db sh -c "$mysql_command"; }
validate_database() {
    [[ $(query 'SELECT DATABASE();') == order_stock_prod ]] || fail 'Expected order_stock_prod database.'
    [[ $(query "SELECT SUBSTRING_INDEX(CURRENT_USER(), '@', 1);") == order_prod ]] || fail 'Expected dedicated order_prod account.'
}

if [[ $operation == backup ]]; then
    parent=$(realpath -m -- "$3")
    case "$parent/" in "$repo_root/"*) fail 'Backups must be stored outside the repository.' ;; esac
    "${compose[@]}" config --quiet
    validate_database
    [[ $(query "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='flyway_schema_history';") == 1 ]] || fail 'Application schema is not initialized.'
    [[ $(query "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_TYPE='BASE TABLE' AND ENGINE <> 'InnoDB';") == 0 ]] || fail 'Consistent backup requires InnoDB tables.'
    table_count=$(query 'SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE();')
    mkdir -p -- "$parent"
    archive=$(mktemp -d -- "$parent/order-stock-$(date -u +%Y%m%dT%H%M%SZ)-XXXXXXXX")
    touch "$archive/INCOMPLETE"
    trap 'printf "Backup incomplete; do not restore: %s\n" "$archive" >&2' ERR
    # shellcheck disable=SC2016 # The DB container supplies the credentials at execution time.
    "${compose[@]}" exec -T db sh -c \
        'MYSQL_PWD="$MYSQL_PASSWORD" exec mysqldump --protocol=TCP --host=127.0.0.1 --user="$MYSQL_USER" --single-transaction --quick --no-tablespaces --set-gtid-purged=OFF --skip-add-drop-table --skip-add-locks "$MYSQL_DATABASE"' |
        gzip > "$archive/database.sql.gz"
    gzip --test "$archive/database.sql.gz"
    printf 'format=order-stock-mysql-v1\ndatabase=order_stock_prod\nproject=%s\ncreated_utc=%s\ntable_count=%s\n' \
        "$project" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$table_count" > "$archive/metadata.txt"
    (cd -- "$archive" && sha256sum database.sql.gz metadata.txt > SHA256SUMS)
    rm -- "$archive/INCOMPLETE"
    trap - ERR
    printf '%s\n' "$archive"
    exit 0
fi

archive=$(realpath -- "$3")
[[ -d $archive && ! -e $archive/INCOMPLETE ]] || fail 'Backup is incomplete or missing.'
for file in database.sql.gz metadata.txt SHA256SUMS; do
    [[ -f $archive/$file && ! -L $archive/$file ]] || fail "Missing regular backup file: $file"
done
[[ $(wc -l < "$archive/SHA256SUMS") -eq 2 ]] || fail 'Unexpected checksum manifest.'
for file in database.sql.gz metadata.txt; do
    [[ $(grep -Ec "^[a-f0-9]{64}  ${file//./\\.}$" "$archive/SHA256SUMS") -eq 1 ]] || fail 'Unexpected checksum manifest.'
done
(cd -- "$archive" && sha256sum --strict --check SHA256SUMS > /dev/null) || fail 'Backup checksum verification failed.'
gzip --test "$archive/database.sql.gz" || fail 'Compressed backup is damaged.'
grep -qx 'format=order-stock-mysql-v1' "$archive/metadata.txt" || fail 'Unsupported backup format.'
grep -qx 'database=order_stock_prod' "$archive/metadata.txt" || fail 'Unexpected backup database.'
expected_tables=$(sed -n 's/^table_count=//p' "$archive/metadata.txt")
[[ $expected_tables =~ ^[1-9][0-9]*$ ]] || fail 'Invalid backup table count.'

"${compose[@]}" config --quiet
running_services=$("${compose[@]}" ps --status running -q app proxy)
[[ -z $running_services ]] || fail 'Stop app and proxy before restoring.'
validate_database
[[ $(query 'SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE();') == 0 ]] || fail 'Target database must be empty; existing data was preserved.'
# No DROP TABLE statements are generated by backup. On an import error, do not retry on the partial DB.
gzip --decompress --stdout "$archive/database.sql.gz" | "${compose[@]}" exec -T db sh -c "$mysql_command"
[[ $(query 'SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE();') == "$expected_tables" ]] || fail 'Restored table count does not match backup.'
# A database snapshot must not resurrect an old authenticated session after disaster recovery.
session_tables=$(query "SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='app_sessions';")
if [[ $session_tables == 1 ]]; then
    query 'DELETE FROM app_sessions;' > /dev/null
    [[ $(query 'SELECT COUNT(*) FROM app_sessions;') == 0 ]] || fail 'Restored sessions were not invalidated.'
fi
printf 'RESTORE OK: %s / order_stock_prod. Start the matching app version and verify readiness.\n' "$project"
